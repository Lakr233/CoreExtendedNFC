    @Test(arguments: [false, true])
    func `Captured T-Money follows the configuration DF and replays balance and history`(automatic: Bool) async throws {
        let transport = MockTransport()
        let ok: (Data) -> ResponseAPDU = { ResponseAPDU(data: $0, sw1: 0x90, sw2: 0x00) }
        let end = ResponseAPDU(data: Data(), sw1: 0x6A, sw2: 0x83)
        transport.apduResponses =
            (automatic ? [ResponseAPDU(data: Data(), sw1: 0x6A, sw2: 0x82)] : []) + [
                ok(hex(configurationFCI)),
                ok(hex(purseFCI)),
                ok(hex("000014B4")),
            ] + transactions.map { ok(hex($0)) } + [end] + taps.map { ok(hex($0)) } + [end]

        let result: TransitBalance
        if automatic {
            result = try await CoreExtendedNFC.readTransitBalance(
                info: CardInfo(type: .smartMX, uid: transport.identifier), transport: transport
            )
        } else {
            result = try await KSX6924Reader(transport: transport).readBalanceAndHistory()
        }
        #expect(result.cardName == "T-Money")
        #expect(result.serialNumber == "0123456789ABCDEF")
        #expect(result.currencyCode == "KRW")
        #expect(result.balanceRaw == 5300)
        try #require(result.transactions.count == 20)
        try #require(result.tapEvents.count == 20)
        #expect(result.transactions.map(\.recordNumber) == Array(1 ... 20))
        #expect(result.tapEvents.map(\.recordNumber) == Array(1 ... 20))
        #expect(result.transactions[0].type == .trip)
        #expect(result.transactions[0].amount == 0)
        #expect(result.transactions[0].balanceAfter == 5300)
        #expect(result.transactions[0].date == nil)
        #expect(result.transactions[1].amount == 1200)
        #expect(result.transactions[4].type == .topup)
        #expect(result.transactions[4].amount == 9000)
        #expect(result.transactions[4].balanceAfter == 11150)
        #expect(result.tapEvents.filter { $0.event == .tapOn }.count == 10)
        #expect(result.tapEvents.filter { $0.event == .tapOff }.count == 10)
        #expect(result.tapEvents.filter { $0.mode == .rail }.count == 6)
        #expect(result.tapEvents.filter { $0.mode == .bus }.count == 14)
        #expect(result.tapEvents.allSatisfy { $0.amount == nil && $0.balanceAfter == nil })
        #expect(result.tapEvents.filter { $0.event == .tapOn }.allSatisfy { $0.distanceMeters == nil })
        #expect(result.tapEvents[0].event == .tapOff)
        #expect(result.tapEvents[0].exitStation == "00009850")
        #expect(result.tapEvents[0].distanceMeters == 5800)
        #expect(result.tapEvents[0].date == Date(timeIntervalSince1970: 1_766_817_590))
        #expect(result.tapEvents[1].entryStation == "00009830")
        #expect(result.tapEvents[2].distanceMeters == 53900)
        #expect(result.tapEvents[4].mode == .bus)
        #expect(result.tapEvents[4].entryStation == "85030950")
        #expect(result.tapEvents[4].date == result.transactions[5].date)
        #expect(result.tapEvents[4].date != nil)
        #expect(result.tapEvents[6].date == result.transactions[6].date)
        #expect(result.tapEvents.dropFirst(7).allSatisfy { $0.date == nil })
        #expect(result.transactions.map(\.rawData) == transactions.map(hex))
        #expect(result.tapEvents.map(\.rawData) == taps.map(hex))
        let start = automatic ? 1 : 0
        #expect(transport.sentAPDUs[start].data == KSX6924Constants.hyundaiAID)
        #expect(transport.sentAPDUs[start + 1].data == KSX6924Constants.tMoneyAID)
        #expect(transport.sentAPDUs[start + 2].ins == KSX6924Constants.INS_GET_BALANCE)
        #expect(transport.sentAPDUs.count == start + 45)
    }

    private func hex(_ text: String) -> Data {
        let chars = Array(text)
        return Data(
            stride(from: 0, to: chars.count, by: 2).map {
                UInt8(String(chars[$0 ... $0 + 1]), radix: 16)!
            })
    }
